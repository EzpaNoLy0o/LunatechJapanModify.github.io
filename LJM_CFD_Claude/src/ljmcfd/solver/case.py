"""OpenFOAM ケースの生成 (定常・非圧縮 RANS、k-ω SST、OpenFOAM Foundation 14)。

辞書の書式は OpenFOAM 14 付属のチュートリアル (incompressibleFluid/drivaerFastback) と
実機での実行結果に合わせてある。

境界条件:

=============== ============================ ============== ===========================
パッチ           速度 U                        圧力 p          乱流 (k, ω, ν_t)
=============== ============================ ============== ===========================
inlet            固定値 (U∞, 0, 0)             勾配ゼロ         固定値 / calculated
outlet           inletOutlet (逆流は 0)         固定値 0         inletOutlet / calculated
sideL/R, top,    slip (すべり壁)               slip            slip
bottom
ground           Moving Ground: 固定値 (U∞,0,0) 勾配ゼロ         壁関数
                 それ以外: noSlip
車体パーツ         noSlip                        勾配ゼロ         壁関数
=============== ============================ ============== ===========================

壁面は全 y+ 域で使える ``nutUSpaldingWallFunction`` を使う (境界層メッシュの有無によらず破綻しない)。
"""

from __future__ import annotations

import shutil
from pathlib import Path

from ..core.jobs import JobError
from .settings import SolverSettings

SLIP_PATCHES = ("sideL", "sideR", "top", "bottom")
FORCES_ALL = "forces"
STOP_FILE = "stop"


def _header(cls: str, obj: str) -> str:
    return (
        "/*--------------------------------*- C++ -*----------------------------------*\\\n"
        "  Generated by LJM CFD (Claude Edition)\n"
        "\\*---------------------------------------------------------------------------*/\n"
        f"FoamFile\n{{\n    format      ascii;\n    class       {cls};\n    object      {obj};\n}}\n\n"
    )


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="ascii", newline="\n") as fh:
        fh.write(text)


def part_patches(patches: list[dict]) -> list[str]:
    return [p["name"] for p in patches if p.get("kind") == "part"]


def forces_name(patch: str) -> str:
    """パーツ別の荷重を出力する function object の名前。"""
    return f"forces_{patch}"


def control_dict(end_time: int, write_interval: int | None = None) -> str:
    interval = write_interval or end_time
    return _header("dictionary", "controlDict") + (
        "solver          incompressibleFluid;\n"
        "startFrom       latestTime;\n"
        "startTime       0;\n"
        "stopAt          endTime;\n"
        f"endTime         {int(end_time)};\n"
        "deltaT          1;\n"
        "writeControl    timeStep;\n"
        f"writeInterval   {int(interval)};\n"
        "purgeWrite      1;\n"
        "writeFormat     binary;\n"
        "writePrecision  8;\n"
        "writeCompression off;\n"
        "timeFormat      general;\n"
        "timePrecision   8;\n"
        "runTimeModifiable true;\n"
    )


def fv_schemes() -> str:
    """離散化スキーム。対流は有界な 2 次風上、勾配はセルリミッタ、拡散は非直交補正を制限して安定化する。"""
    return _header("dictionary", "fvSchemes") + """ddtSchemes
{
    default         steadyState;
}

gradSchemes
{
    default         Gauss linear;
    limited         cellLimited Gauss linear 1;
    grad(U)         $limited;
    grad(k)         $limited;
    grad(omega)     $limited;
}

divSchemes
{
    default         none;
    div(phi,U)      bounded Gauss linearUpwind limited;
    turbulence      bounded Gauss limitedLinear 1;
    div(phi,k)      $turbulence;
    div(phi,omega)  $turbulence;
    div((nuEff*dev2(T(grad(U))))) Gauss linear;
}

laplacianSchemes
{
    default         Gauss linear limited corrected 0.5;
}

interpolationSchemes
{
    default         linear;
}

snGradSchemes
{
    default         limited corrected 0.5;
}

wallDist
{
    method          meshWave;
}
"""


def fv_solution(settings: SolverSettings, non_ortho_correctors: int) -> str:
    tol = settings.residual_tolerance
    return _header("dictionary", "fvSolution") + f"""solvers
{{
    p
    {{
        solver          GAMG;
        smoother        GaussSeidel;
        tolerance       1e-7;
        relTol          0.05;
    }}

    Phi
    {{
        $p;
    }}

    "(U|k|omega)"
    {{
        solver          smoothSolver;
        smoother        symGaussSeidel;
        tolerance       1e-8;
        relTol          0.1;
    }}
}}

SIMPLE
{{
    nNonOrthogonalCorrectors {int(non_ortho_correctors)};
    consistent      no;

    residualControl
    {{
        p               {tol:g};
        U               {tol:g};
        "(k|omega)"     {tol:g};
    }}
}}

potentialFlow
{{
    nNonOrthogonalCorrectors 10;
}}

relaxationFactors
{{
    fields
    {{
        p               {settings.relax_p:g};
    }}
    equations
    {{
        U               {settings.relax_u:g};
        "(k|omega)"     {settings.relax_turbulence:g};
    }}
}}
"""


def decompose_par_dict(n_procs: int) -> str:
    return _header("dictionary", "decomposeParDict") + f"numberOfSubdomains {int(n_procs)};\n\nmethod          scotch;\n"


def functions_dict(patches: list[dict], rho: float) -> str:
    """実行中に出力する量: 荷重 (全体とパーツ別)、残差、流入出の流量、y+、壁面せん断、渦度、Q 値。"""
    parts = part_patches(patches)
    if not parts:
        raise JobError("メッシュに車体パーツの壁面パッチがありません")

    def forces(name: str, names: list[str]) -> str:
        return (
            f"{name}\n{{\n    type            forces;\n    libs            (\"libforces.so\");\n"
            "    writeControl    timeStep;\n    writeInterval   1;\n"
            f"    patches         ({' '.join(names)});\n"
            f"    rho             rhoInf;\n    rhoInf          {rho:.8g};\n    CofR            (0 0 0);\n}}\n\n"
        )

    text = _header("dictionary", "functions") + forces(FORCES_ALL, parts)
    if len(parts) > 1:
        text += "".join(forces(forces_name(p), [p]) for p in parts)
    text += (
        "#includeFunc residuals(name=residuals, fields=(p U k omega))\n"
        "#includeFunc patchFlowRate(name=flowInlet, patch=inlet)\n"
        "#includeFunc patchFlowRate(name=flowOutlet, patch=outlet)\n"
        "#includeFunc yPlus\n"
        "#includeFunc wallShearStress\n"
        "#includeFunc vorticity\n"
        "#includeFunc Q\n\n"
        # ケースフォルダに stop という名前のファイルを置くと、その反復の結果を書き出して終了する
        "stopAtFile\n{\n    type            stopAtFile;\n    libs            (\"libutilityFunctionObjects.so\");\n"
        f"    file            \"$FOAM_CASE/{STOP_FILE}\";\n    action          writeNow;\n}}\n"
    )
    return text


def _patch_kind(patch: dict) -> str:
    """境界条件の種類: inlet / outlet / slip / ground / wall。"""
    name = patch["name"]
    if patch.get("kind") == "part":
        return "wall"
    if name in ("inlet", "outlet", "ground"):
        return name
    if name in SLIP_PATCHES:
        return "slip"
    raise JobError(f"境界条件を決められないパッチがあります: {name}")


def _field(cls: str, name: str, dimensions: str, internal: str, patches: list[dict], entries: dict[str, str]) -> str:
    lines = [_header(cls, name), f"dimensions      [{dimensions}];\n\ninternalField   uniform {internal};\n\nboundaryField\n{{\n"]
    for patch in patches:
        body = entries[_patch_kind(patch)]
        lines.append(f"    {patch['name']}\n    {{\n")
        lines.extend(f"        {line}\n" for line in body.split("\n"))
        lines.append("    }\n")
    lines.append("}\n")
    return "".join(lines)


def field_files(patches: list[dict], speed: float, k: float, omega: float, moving_ground: bool) -> dict[str, str]:
    """初期・境界条件ファイルの内容 (ファイル名 → テキスト)。"""
    u = f"({speed:.8g} 0 0)"
    ground_u = f"type            fixedValue;\nvalue           uniform {u};" if moving_ground else "type            noSlip;"
    slip = "type            slip;"
    return {
        "U": _field("volVectorField", "U", "velocity", u, patches, {
            "inlet": f"type            fixedValue;\nvalue           uniform {u};",
            "outlet": f"type            inletOutlet;\ninletValue      uniform (0 0 0);\nvalue           uniform {u};",
            "slip": slip, "ground": ground_u, "wall": "type            noSlip;",
        }),
        "p": _field("volScalarField", "p", "kinematicPressure", "0", patches, {
            "inlet": "type            zeroGradient;",
            "outlet": "type            fixedValue;\nvalue           uniform 0;",
            "slip": slip, "ground": "type            zeroGradient;", "wall": "type            zeroGradient;",
        }),
        "k": _field("volScalarField", "k", "turbulentKineticEnergy", f"{k:.8g}", patches, {
            "inlet": f"type            fixedValue;\nvalue           uniform {k:.8g};",
            "outlet": f"type            inletOutlet;\ninletValue      uniform {k:.8g};\nvalue           uniform {k:.8g};",
            "slip": slip,
            "ground": f"type            kqRWallFunction;\nvalue           uniform {k:.8g};",
            "wall": f"type            kqRWallFunction;\nvalue           uniform {k:.8g};",
        }),
        "omega": _field("volScalarField", "omega", "turbulentOmega", f"{omega:.8g}", patches, {
            "inlet": f"type            fixedValue;\nvalue           uniform {omega:.8g};",
            "outlet": f"type            inletOutlet;\ninletValue      uniform {omega:.8g};\nvalue           uniform {omega:.8g};",
            "slip": slip,
            "ground": f"type            omegaWallFunction;\nvalue           uniform {omega:.8g};",
            "wall": f"type            omegaWallFunction;\nvalue           uniform {omega:.8g};",
        }),
        "nut": _field("volScalarField", "nut", "turbulentViscosity", "0", patches, {
            "inlet": "type            calculated;\nvalue           uniform 0;",
            "outlet": "type            calculated;\nvalue           uniform 0;",
            "slip": slip,
            "ground": "type            nutUSpaldingWallFunction;\nvalue           uniform 0;",
            "wall": "type            nutUSpaldingWallFunction;\nvalue           uniform 0;",
        }),
    }


def latest_time(case_dir: str | Path) -> int:
    """ケースにある最新の時刻 (反復数)。初期状態のみなら 0。"""
    latest = 0
    for child in Path(case_dir).iterdir() if Path(case_dir).is_dir() else []:
        if child.is_dir() and child.name.isdigit():
            latest = max(latest, int(child.name))
    return latest


def clean_case(case_dir: Path) -> None:
    """前回の計算結果 (時刻フォルダ・分割・後処理・ログ) を消す。"""
    for child in case_dir.iterdir():
        if child.is_dir() and (child.name.isdigit() or child.name.startswith("processor") or child.name in ("postProcessing", "VTK", "0")):
            shutil.rmtree(child, ignore_errors=True)
        elif child.is_file() and (child.name.startswith("log.") or child.name == STOP_FILE):
            child.unlink(missing_ok=True)


def write_case(case_dir: str | Path, mesh_dir: str | Path, patches: list[dict], flow: dict, moving_ground: bool,
               settings: SolverSettings, max_non_ortho: float, n_procs: int) -> dict:
    """ケース一式を書き出す。戻り値: {"start_time", "end_time", "non_ortho_correctors", "continued"}

    flow: {"speed", "nu", "rho", "k", "omega"} (SI 単位)
    ``settings.continue_run`` が真で前回の解があれば、場と履歴を残したまま反復を追加する。
    """
    case_dir, mesh_dir = Path(case_dir), Path(mesh_dir)
    source_mesh = mesh_dir / "polyMesh"
    if not (source_mesh / "points").is_file():
        raise JobError(f"メッシュ (polyMesh) が見つかりません: {source_mesh}")
    case_dir.mkdir(parents=True, exist_ok=True)

    start = latest_time(case_dir) if settings.continue_run else 0
    continued = start > 0
    if not continued:
        clean_case(case_dir)
        target_mesh = case_dir / "constant" / "polyMesh"
        shutil.rmtree(target_mesh, ignore_errors=True)
        shutil.copytree(source_mesh, target_mesh)
        for name, text in field_files(patches, flow["speed"], flow["k"], flow["omega"], moving_ground).items():
            _write(case_dir / "0" / name, text)
    else:
        (case_dir / STOP_FILE).unlink(missing_ok=True)
        shutil.rmtree(case_dir / "VTK", ignore_errors=True)
        for child in case_dir.glob("processor*"):
            shutil.rmtree(child, ignore_errors=True)

    correctors = settings.resolved_non_ortho_correctors(max_non_ortho)
    end = start + settings.iterations
    _write(case_dir / "system" / "controlDict", control_dict(end))
    _write(case_dir / "system" / "fvSchemes", fv_schemes())
    _write(case_dir / "system" / "fvSolution", fv_solution(settings, correctors))
    _write(case_dir / "system" / "decomposeParDict", decompose_par_dict(max(n_procs, 1)))
    _write(case_dir / "system" / "functions", functions_dict(patches, flow["rho"]))
    _write(case_dir / "constant" / "momentumTransport",
           _header("dictionary", "momentumTransport") + "simulationType  RAS;\n\nRAS\n{\n    model           kOmegaSST;\n    turbulence      on;\n}\n")
    _write(case_dir / "constant" / "physicalProperties",
           _header("dictionary", "physicalProperties") + f"viscosityModel  constant;\n\nnu              {flow['nu']:.8g};\n")
    return {"start_time": start, "end_time": end, "non_ortho_correctors": correctors, "continued": continued}
