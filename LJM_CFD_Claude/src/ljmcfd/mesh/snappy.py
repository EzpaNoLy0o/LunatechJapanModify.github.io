SNAPPY_PRESETS = {"coarse": 150.0, "standard": 300.0, "fine": 425.0}
#: 境界層の層数 (プリセットごと)
SNAPPY_LAYERS = {"coarse": 2, "standard": 3, "fine": 3}
GROUND_TOLERANCE = 0.002     # これより地面に近いパーツを「接地している」とみなす [m]
