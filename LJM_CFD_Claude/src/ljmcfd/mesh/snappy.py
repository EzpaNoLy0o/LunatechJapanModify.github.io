"""STL 形状から、OpenFOAM の snappyHexMesh で風洞メッシュを作る (v0.8)。

Gmsh の経路 (``gmsh_job.py``) は STEP / IGES の厳密な形状 (B-Rep) を前提にしている。
三角形の集まりである STL には、外部空力で標準的な snappyHexMesh の手順を使う
(OpenFOAM 同梱の DrivAer チュートリアルと同じ流れ)::

    blockMesh (背景の六面体格子) → surfaceFeatures (稜線) → snappyHexMesh (切り抜き・表面合わせ・境界層)
    → checkMesh (品質) → foamToVTK (表示用の表面)

* パーツごとの STL を 1 つのパッチにする (荷重をパーツ別に出せる)。風洞の外周は Gmsh の経路と同じ名前
  (inlet / outlet / sideL / sideR / top / ground) なので、解析の設定はそのまま使える。
* 地面に「線」で接するパーツ (タイヤ) は、接地部の沈み込み量だけ下げて有限の接地面を作る。
  地面から離れているパーツ (車体) は動かさない (車高を変えない)。
* 格子は「表面のセルサイズ」から決める: 背景の格子 = 表面サイズ × 2^レベル。車体のまわり・後流・遠方の
  直方体ごとに細分化のレベルを下げていく。
* OpenFOAM の実行環境 (WSL / ネイティブ) は解析と同じものを使う。
"""

